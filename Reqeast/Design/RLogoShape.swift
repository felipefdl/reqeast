    func path(in rect: CGRect) -> Path {
        var path = Path()
        buildPath(&path)
        let sx = rect.width / Self.svgWidth
        let sy = rect.height / Self.svgHeight
        return path.applying(CGAffineTransform(scaleX: sx, y: sy))
    }
}

